from io import BytesIO
from collections.abc import Mapping

import numpy as np


def mesh_to_obj(mesh) -> tuple[bytes, int, int]:
    vertices = _as_numpy(mesh["verts"] if isinstance(mesh, dict) else mesh.verts)
    faces = _as_numpy(mesh["faces"] if isinstance(mesh, dict) else mesh.faces)
    if vertices.ndim != 2 or vertices.shape[1] != 3:
        raise ValueError(f"Expected Nx3 vertices, got shape {vertices.shape}.")
    if faces.ndim != 2 or faces.shape[1] != 3:
        raise ValueError(f"Expected Mx3 triangular faces, got shape {faces.shape}.")
    if len(vertices) == 0 or len(faces) == 0:
        raise ValueError("Shap-E mesh has no vertices or faces.")
    if not np.isfinite(vertices).all():
        raise ValueError("Shap-E mesh contains non-finite vertices.")
    if faces.min() < 0 or faces.max() >= len(vertices):
        raise ValueError("Shap-E mesh face index is out of bounds.")

    channels = (
        mesh.get("vertex_channels")
        if isinstance(mesh, dict)
        else getattr(mesh, "vertex_channels", None)
    )
    colors = None
    if isinstance(channels, Mapping) and all(
        channel in channels for channel in ("R", "G", "B")
    ):
        colors = np.stack(
            [_as_numpy(channels[channel]) for channel in ("R", "G", "B")],
            axis=1,
        )
        if colors.shape != vertices.shape or not np.isfinite(colors).all():
            colors = None

    buffer = BytesIO()
    buffer.write(b"# Wavefront OBJ generated by openai/shap-e\n")
    if colors is None:
        for x, y, z in vertices:
            buffer.write(f"v {x:.7g} {y:.7g} {z:.7g}\n".encode("ascii"))
    else:
        for (x, y, z), (r, g, b) in zip(vertices, colors):
            buffer.write(
                f"v {x:.7g} {y:.7g} {z:.7g} {r:.7g} {g:.7g} {b:.7g}\n".encode(
                    "ascii"
                )
            )
    for a, b, c in faces:
        buffer.write(f"f {a + 1} {b + 1} {c + 1}\n".encode("ascii"))
    return buffer.getvalue(), len(vertices), len(faces)


def _as_numpy(value) -> np.ndarray:
    if hasattr(value, "detach"):
        return value.detach().cpu().numpy()
    return np.asarray(value)
